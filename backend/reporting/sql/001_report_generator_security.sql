CREATE TABLE IF NOT EXISTS pulsar.t_permission
(
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code TEXT NOT NULL,
    permission_title TEXT NOT NULL,
    page_key TEXT NULL,
    scope_type TEXT NOT NULL DEFAULT 'PAGE',
    scope_key TEXT NULL,
    subsystem_key TEXT NULL,
    permission_desc TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NULL REFERENCES pulsar.t_user(c_user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by UUID NULL REFERENCES pulsar.t_user(c_user_id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NULL,

    CONSTRAINT t_permission_scope_type_ck
        CHECK (scope_type IN ('SYSTEM', 'SUBSYSTEM', 'PAGE')),

    CONSTRAINT t_permission_scope_ck
        CHECK (
            (scope_type = 'SYSTEM' AND scope_key IS NULL AND page_key IS NULL AND subsystem_key IS NULL)
            OR
            (scope_type = 'SUBSYSTEM' AND NULLIF(BTRIM(scope_key), '') IS NOT NULL
                AND (subsystem_key IS NULL OR subsystem_key = scope_key))
            OR
            (
                scope_type = 'PAGE'
                AND NULLIF(BTRIM(scope_key), '') IS NOT NULL
                AND page_key IS NOT NULL
                AND scope_key = page_key
            )
        ),

    CONSTRAINT t_permission_id_code_uq
        UNIQUE (permission_id, permission_code),

    CONSTRAINT t_permission_page_fk
        FOREIGN KEY (page_key)
        REFERENCES pulsar.dynamic_page(page_key)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS t_permission_code_scope_uq
    ON pulsar.t_permission
    (
        permission_code,
        scope_type,
        COALESCE(scope_key, ''),
        COALESCE(page_key, '')
    );

CREATE INDEX IF NOT EXISTS t_permission_page_idx
    ON pulsar.t_permission(page_key)
    WHERE page_key IS NOT NULL;

-- ============================================================
-- User Permission Grants
-- A user may receive the same permission in multiple periods.
-- No uniqueness constraint is intentionally placed on user +
-- permission. Validity uses a half-open interval [from, until).
-- ============================================================

CREATE TABLE IF NOT EXISTS pulsar.t_permit_usracc
(
    permit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    c_user_id UUID NOT NULL
        REFERENCES pulsar.t_user(c_user_id) ON DELETE RESTRICT,
    permission_id BIGINT NOT NULL,
    permission_code TEXT NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_until TIMESTAMPTZ NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    granted_by UUID NOT NULL
        REFERENCES pulsar.t_user(c_user_id) ON DELETE RESTRICT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_by UUID NULL
        REFERENCES pulsar.t_user(c_user_id) ON DELETE RESTRICT,
    revoked_at TIMESTAMPTZ NULL,
    grant_reason TEXT NULL,

    CONSTRAINT t_permit_usracc_permission_fk
        FOREIGN KEY (permission_id, permission_code)
        REFERENCES pulsar.t_permission(permission_id, permission_code)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT t_permit_usracc_validity_ck
        CHECK (valid_until IS NULL OR valid_until > valid_from),

    CONSTRAINT t_permit_usracc_revocation_ck
        CHECK (
            (
                is_active IS TRUE
                AND revoked_by IS NULL
                AND revoked_at IS NULL
            )
            OR
            (
                is_active IS FALSE
                AND revoked_by IS NOT NULL
                AND revoked_at IS NOT NULL
            )
        )
);

CREATE INDEX IF NOT EXISTS t_permit_usracc_effective_idx
    ON pulsar.t_permit_usracc
    (c_user_id, permission_id, valid_from, valid_until)
    WHERE is_active IS TRUE;

CREATE INDEX IF NOT EXISTS t_permit_usracc_grantor_idx
    ON pulsar.t_permit_usracc(granted_by, granted_at DESC);

