-- ============================================================
-- Append-only audit log tables
-- log_state: I = INSERT, U = UPDATE, D = DELETE.
-- old_data/new_data preserve complete row snapshots.
-- ============================================================

DO $$
DECLARE
    v_table_name TEXT;
BEGIN
    FOREACH v_table_name IN ARRAY ARRAY[
        't_permission',
        't_permit_usracc',
        't_report',
        't_report_column',
        't_report_filter',
        't_report_share',
        't_report_version'
    ]
    LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS pulsar_log.%I (
                audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                log_state CHAR(1) NOT NULL CHECK (log_state IN (''I'', ''U'', ''D'')),
                log_user UUID NOT NULL,
                log_ip INET NOT NULL,
                log_date TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
                old_data JSONB NULL,
                new_data JSONB NULL
            )',
            v_table_name || '_log'
        );
    END LOOP;
END;
$$;

-- ============================================================
-- Generic audit trigger
-- The application sets transaction-local values:
--   pulsar.log_user = authenticated t_user.c_user_id
--   pulsar.log_ip   = request.client.host
-- ============================================================

CREATE OR REPLACE FUNCTION pulsar.fn_audit_record_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
    v_old_data JSONB;
    v_new_data JSONB;
    v_log_state CHAR(1);
    v_log_user UUID;
    v_log_ip INET;
    v_log_table TEXT;
BEGIN
    v_log_user := NULLIF(
        current_setting('pulsar.log_user', TRUE),
        ''
    )::UUID;

    v_log_ip := NULLIF(
        current_setting('pulsar.log_ip', TRUE),
        ''
    )::INET;

    IF v_log_user IS NULL THEN
        RAISE EXCEPTION
            'Audit identity is required: set pulsar.log_user before modifying %.%',
            TG_TABLE_SCHEMA,
            TG_TABLE_NAME;
    END IF;

    IF v_log_ip IS NULL THEN
        RAISE EXCEPTION
            'Audit client IP is required: set pulsar.log_ip before modifying %.%',
            TG_TABLE_SCHEMA,
            TG_TABLE_NAME;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pulsar.t_user
        WHERE c_user_id = v_log_user
          AND c_user_active IS TRUE
    ) THEN
        RAISE EXCEPTION
            'Audit user % does not exist in pulsar.t_user.',
            v_log_user;
    END IF;

    IF TG_OP = 'INSERT' THEN
        v_old_data := NULL;
        v_new_data := TO_JSONB(NEW);
        v_log_state := 'I';
    ELSIF TG_OP = 'UPDATE' THEN
        v_old_data := TO_JSONB(OLD);
        v_new_data := TO_JSONB(NEW);
        v_log_state := 'U';
    ELSIF TG_OP = 'DELETE' THEN
        v_old_data := TO_JSONB(OLD);
        v_new_data := NULL;
        v_log_state := 'D';
    ELSE
        RAISE EXCEPTION 'Unsupported audit operation: %', TG_OP;
    END IF;

    v_log_table := TG_TABLE_NAME || '_log';

    EXECUTE FORMAT(
        'INSERT INTO pulsar_log.%I
            (log_state, log_user, log_ip, log_date, old_data, new_data)
         VALUES ($1, $2, $3, clock_timestamp(), $4, $5)',
        v_log_table
    )
    USING
        v_log_state,
        v_log_user,
        v_log_ip,
        v_old_data,
        v_new_data;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$function$;

DO $$
DECLARE
    v_table_name TEXT;
BEGIN
    FOREACH v_table_name IN ARRAY ARRAY[
        't_permission',
        't_permit_usracc',
        't_report',
        't_report_column',
        't_report_filter',
        't_report_share',
        't_report_version'
    ]
    LOOP
        EXECUTE FORMAT(
            'DROP TRIGGER IF EXISTS %I ON pulsar.%I',
            'trg_audit_' || v_table_name,
            v_table_name
        );

        EXECUTE FORMAT(
            'CREATE TRIGGER %I
             AFTER INSERT OR UPDATE OR DELETE ON pulsar.%I
             FOR EACH ROW
             EXECUTE FUNCTION pulsar.fn_audit_record_change()',
            'trg_audit_' || v_table_name,
            v_table_name
        );
    END LOOP;
END;
$$;

