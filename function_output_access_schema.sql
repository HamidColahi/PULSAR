BEGIN;

CREATE TABLE IF NOT EXISTS pulsar.t_function_output_access
(
    access_id bigint GENERATED BY DEFAULT AS IDENTITY,
    output_config_id bigint NOT NULL,
    resource_code varchar(100) NOT NULL,
    access_mode varchar(20) NOT NULL,
    access_options jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active boolean NOT NULL DEFAULT true,
    priority integer NOT NULL DEFAULT 10,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_function_output_access
        PRIMARY KEY (access_id),

    CONSTRAINT uq_function_output_access_resource
        UNIQUE (output_config_id, resource_code),

    CONSTRAINT ck_function_output_access_resource_code
        CHECK (length(btrim(resource_code)) > 0),

    CONSTRAINT ck_function_output_access_mode
        CHECK (access_mode IN ('READ', 'SEARCH')),

    CONSTRAINT ck_function_output_access_options
        CHECK (jsonb_typeof(access_options) = 'object'),

    CONSTRAINT ck_function_output_access_priority
        CHECK (priority > 0),

    CONSTRAINT fk_function_output_access_config
        FOREIGN KEY (output_config_id)
        REFERENCES pulsar.t_function_output_config (output_config_id)
        ON DELETE CASCADE
);

COMMENT ON TABLE pulsar.t_function_output_access IS
    'Authorized data resources available to an Avatar for a Function output configuration / منابع داده مجاز برای آواتار در پیکربندی خروجی تابع';

COMMENT ON COLUMN pulsar.t_function_output_access.access_id IS
    'Unique Function output access identifier / شناسه یکتای دسترسی خروجی تابع';

COMMENT ON COLUMN pulsar.t_function_output_access.output_config_id IS
    'Owning Function output configuration / شناسه پیکربندی خروجی تابع';

COMMENT ON COLUMN pulsar.t_function_output_access.resource_code IS
    'Stable resource provider code resolved by the backend / کد پایدار منبع که توسط Backend بازیابی می‌شود';

COMMENT ON COLUMN pulsar.t_function_output_access.access_mode IS
    'Permitted resource operation: READ or SEARCH / نوع عملیات مجاز روی منبع';

COMMENT ON COLUMN pulsar.t_function_output_access.access_options IS
    'Provider-specific, validated resource options / تنظیمات اختصاصی و اعتبارسنجی‌شده منبع';

COMMENT ON COLUMN pulsar.t_function_output_access.is_active IS
    'Whether this resource permission is active / وضعیت فعال بودن مجوز منبع';

CREATE INDEX IF NOT EXISTS ix_function_output_access_active
    ON pulsar.t_function_output_access
       (output_config_id, is_active, priority);

