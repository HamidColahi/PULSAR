INSERT INTO pulsar.t_function_output_access
(
    output_config_id,
    resource_code,
    access_mode,
    access_options,
    is_active,
    priority
)
SELECT
    config.output_config_id,
    resource.resource_code,
    resource.access_mode,
    resource.access_options,
    resource.is_active,
    resource.priority
FROM pulsar.t_function_output_config config
CROSS JOIN (
    VALUES
    (
        'COLONY_TABLE_1',
        'READ',
        '{"max_rows": 50, "include_guidance_metadata": true}'::jsonb,
        true,
        10
    ),
    (
        'COLONY_GUIDANCE_PDF',
        'READ',
        '{"max_pages": 80, "max_text_chars": 30000}'::jsonb,
        true,
        20
    ),
    (
        'COLONY_RULE_SEARCH',
        'SEARCH',
        '{"search_fields": ["inquiry", "reaction", "event", "action", "rp", "pbi_sbi"], "max_results": 20, "cross_backlog": true}'::jsonb,
        true,
        30
    ),
    (
        'COLONY_RELATED_RULES',
        'SEARCH',
        '{"search_fields": ["inquiry", "reaction", "event", "action", "rp", "pbi_sbi"], "max_results": 20, "cross_backlog": true}'::jsonb,
        true,
        40
    )
) AS resource (
    resource_code,
    access_mode,
    access_options,
    is_active,
    priority
)
WHERE config.schema_name = 'pulsar'
  AND config.function_name = 'fn_colony_guidance'
  AND config.config_code = 'COLONY_GUIDANCE_JSON'
  AND config.is_active = TRUE
ON CONFLICT (output_config_id, resource_code)
DO UPDATE SET
    access_mode = EXCLUDED.access_mode,
    access_options = EXCLUDED.access_options,
    is_active = EXCLUDED.is_active,
    priority = EXCLUDED.priority,
    updated_at = CURRENT_TIMESTAMP;

COMMIT;
